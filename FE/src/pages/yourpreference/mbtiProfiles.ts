export type MbtiCode = keyof typeof MBTI_PROFILES;

function normalizeCode(raw: unknown): string {
  return String(raw ?? "").trim().toUpperCase();
}

export function resolveMbtiProfile(code: unknown) {
  const key = normalizeCode(code);
  return (MBTI_PROFILES as Record<string, MbtiProfile | undefined>)[key] ?? null;
}

export function buildFallbackProfile(code: unknown): MbtiProfile {
  const key = normalizeCode(code) || "UNKNOWN";
  return {
    title: "새로운 유형 발견?",
    tagline: `아직 이 MBTI 코드(${key})에 대한 해석이 도착하지 않았어요!`,
    description:
      `서버에서 "${key}" 라는 신비한 코드가 내려왔네요.\n` +
      `개발자님이 얼른 해석을 추가해줘야 볼 수 있어요! 조금만 기다려주세요.`,
    strengths: ["미지의 잠재력"],
    watchouts: ["아직 데이터 없음"],
    tip: "개발자에게 '이거 안 나와요!'라고 제보해주세요.",
  };
}